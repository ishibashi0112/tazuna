/**
 * includePlanner(tazuna init が拡張子から include / exclude を決める。v0.18.0)の単体テスト。
 */

import { suite, test } from "vitest";
import * as assert from "node:assert";
import { looksGenerated, planInclude, type PlannerFile } from "../../src/pack/includePlanner.ts";
import { globToRegExp } from "../../src/pack/globMatcher.ts";

/** パス → 内容。大きさは内容の長さ */
function plan(files: Record<string, string>, alwaysInclude: readonly string[] = []) {
  const list: PlannerFile[] = Object.entries(files).map(([relativePath, content]) => ({
    relativePath,
    size: content.length,
  }));
  const read: string[] = [];
  const result = planInclude(
    {
      files: list,
      readHead: (relativePath) => {
        read.push(relativePath);
        return files[relativePath]?.slice(0, 4096);
      },
    },
    { alwaysInclude },
  );
  return { result, read };
}

/** 設定の include / exclude で、パックに入るか(collectGitFiles と同じ判定) */
function packed(result: ReturnType<typeof plan>["result"], relativePath: string): boolean {
  return (
    result.include.some((glob) => globToRegExp(glob).test(relativePath)) &&
    !result.exclude.some((glob) => globToRegExp(glob).test(relativePath))
  );
}

suite("includePlanner: 種類ごとの扱い", () => {
  test("Python のプロジェクト: ソース・設定・文書を include に、データとノートブックは入れない", () => {
    const { result } = plan({
      "manage.py": "import os\n",
      "shop/models.py": "class Order: pass\n",
      "shop/views.py": "def view(): pass\n",
      "shop/templates/order.html": "<h1>x</h1>\n",
      "static/js/app.js": "1;\n",
      "static/js/jquery.min.js": "/*! jQuery */x\n",
      "pyproject.toml": "[project]\n",
      "requirements.txt": "django\n",
      "README.md": "# shop\n",
      "data/users.csv": "id,email\n1,a@example.com\n",
      "notebooks/analysis.ipynb": '{"cells": []}',
    });
    assert.deepStrictEqual(result.include, [
      "**/*.py",
      "**/*.html",
      "**/*.js",
      "**/*.md",
      "**/*.toml",
      "**/*.txt",
    ]);
    assert.deepStrictEqual(result.exclude, ["**/*.min.js"]);
    assert.deepStrictEqual(result.languages, [
      { name: "Python", count: 3 },
      { name: "HTML", count: 1 },
      { name: "JavaScript", count: 1 },
    ]);
    assert.deepStrictEqual(
      result.omitted.map((entry) => [entry.label, entry.count, entry.example]),
      [
        [".csv", 1, "data/users.csv"],
        [".ipynb", 1, "notebooks/analysis.ipynb"],
      ],
    );
    assert.ok(!packed(result, "data/users.csv"));
    assert.ok(!packed(result, "static/js/jquery.min.js"));
    assert.ok(packed(result, "shop/models.py"));
    assert.strictEqual(result.includedCount, 8);
  });

  test("鍵・認証情報のファイルは中身を読まずに外す。include の拡張子に一致するもの(credentials.json)はパスで exclude に書く", () => {
    const { result, read } = plan({
      "src/app.ts": "export {};\n",
      "package.json": "{}\n",
      "config/credentials.json": '{"key": "x"}\n',
      "certs/dev-key.pem": "-----BEGIN PRIVATE KEY-----\n",
      ".npmrc": "//registry/:_authToken=x\n",
      "deploy/id_rsa": "-----BEGIN OPENSSH PRIVATE KEY-----\n",
      "infra/prod.tfvars": 'password = "x"\n',
      "signing/App.snk": "\u0007\u0002",
    });
    assert.deepStrictEqual(result.include, ["**/*.ts", "**/*.json"]);
    assert.deepStrictEqual(result.exclude, ["config/credentials.json"]);
    for (const secret of ["config/credentials.json", "certs/dev-key.pem", ".npmrc", "deploy/id_rsa", "infra/prod.tfvars", "signing/App.snk"]) {
      assert.ok(!packed(result, secret), secret);
      assert.ok(!read.includes(secret), `${secret} は読まない`);
    }
    assert.ok(result.omitted.every((entry) => entry.reason === "鍵・証明書・認証情報のファイル"));
  });

  test("他から取り込んだコード(vendor/)・生成コードを exclude に。外したものにしか無い拡張子は include に書かない", () => {
    const { result } = plan({
      "go.mod": "module x\n",
      "cmd/main.go": "package main\n",
      "vendor/github.com/a/b/b.go": "package b\n",
      "vendor/modules.txt": "# a\n",
      "api/service.pb.go": "// Code generated by protoc-gen-go. DO NOT EDIT.\npackage api\n",
      "internal/mock.go": "// Code generated by MockGen. DO NOT EDIT.\npackage internal\n",
      "Makefile": "build:\n\tgo build\n",
    });
    assert.deepStrictEqual(result.include, ["**/*.go", "**/go.mod", "**/Makefile"]);
    assert.deepStrictEqual(result.exclude, ["vendor/**", "**/*.pb.go", "internal/mock.go"]);
    assert.deepStrictEqual(
      result.excluded.map((entry) => [entry.pattern, entry.reason, entry.count]),
      [
        ["vendor/**", "他から取り込んだコード", 1],
        ["**/*.pb.go", "生成コード", 1],
        ["internal/mock.go", "生成コード", 1],
      ],
    );
    assert.deepStrictEqual(result.languages, [{ name: "Go", count: 1 }]);
  });

  test("同じ名前の取り込んだコードのディレクトリが複数の場所にあれば **/<名前>/** にまとめる", () => {
    const { result } = plan({
      "a/vendor/x.php": "<?php\n",
      "b/vendor/y.php": "<?php\n",
      "src/Order.php": "<?php\n",
    });
    assert.deepStrictEqual(result.exclude, ["**/vendor/**"]);
    assert.ok(packed(result, "src/Order.php"));
    assert.ok(!packed(result, "b/vendor/y.php"));
  });

  test("拡張子の無い既知の名前・Dockerfile の派生・shebang のスクリプト", () => {
    const { result } = plan({
      "Dockerfile": "FROM node\n",
      "docker/Dockerfile.dev": "FROM node\n",
      "Jenkinsfile": "pipeline {}\n",
      "gradlew": "#!/bin/sh\n",
      "bin/serve": "#!/usr/bin/env python3\nprint(1)\n",
      "tools/notes": "メモ\n",
      ".gitignore": "dist/\n",
    });
    assert.deepStrictEqual(result.include, [
      "**/.gitignore",
      "**/Dockerfile*",
      "**/gradlew",
      "**/Jenkinsfile",
      "bin/serve",
    ]);
    assert.deepStrictEqual(result.languages, [{ name: "Python", count: 1 }]);
    assert.deepStrictEqual(
      result.omitted.map((entry) => [entry.label, entry.reason]),
      [["notes", "種類が分からない"]],
    );
  });

  test("バイナリ(先頭に NUL)・読めないもの・空の種類の分からないものは黙って飛ばし、種類の分からない拡張子は入れないものとして残す", () => {
    const { result } = plan({
      "src/a.py": "x = 1\n",
      "gradle/wrapper/gradle-wrapper.jar": "PK\u0003\u0004\u0000\u0000",
      "src/.gitkeep": "",
      "tests/__snapshots__/a.snap": "exports[`a`] = 1;\n",
    });
    assert.deepStrictEqual(result.include, ["**/*.py"]);
    assert.deepStrictEqual(
      result.omitted.map((entry) => entry.label),
      [".snap"],
    );
  });

  test("alwaysInclude はファイルが無くても書く(Markdown・設定ファイル自身)", () => {
    const { result } = plan({ "main.rs": "fn main() {}\n" }, ["**/*.md", "**/.gitignore", "tazuna.config.json"]);
    assert.deepStrictEqual(result.include, ["**/*.rs", "**/*.md", "**/.gitignore", "tazuna.config.json"]);
  });

  test("言語は件数の多い順に並べ、include も言語の拡張子を件数の多い順に置く", () => {
    const { result } = plan({
      "a.ts": "1\n",
      "b.ts": "1\n",
      "c.tsx": "1\n",
      "d.tsx": "1\n",
      "e.tsx": "1\n",
      "x.json": "{}\n",
    });
    assert.deepStrictEqual(result.include, ["**/*.tsx", "**/*.ts", "**/*.json"]);
    assert.deepStrictEqual(result.languages, [{ name: "TypeScript", count: 5 }]);
  });

  test("大きさの合計と大きいもの(最大 3 件)", () => {
    const { result } = plan({
      "a.py": "x".repeat(50),
      "b.py": "x".repeat(300),
      "c.py": "x".repeat(200),
      "d.py": "x".repeat(100),
      "e.min.js": "x".repeat(999),
    });
    assert.strictEqual(result.includedBytes, 650);
    assert.deepStrictEqual(
      result.largest.map((file) => file.relativePath),
      ["b.py", "c.py", "d.py"],
    );
  });
});

suite("includePlanner: 生成コードの印", () => {
  test("強い印だけを生成コードとみなす", () => {
    assert.ok(looksGenerated("// Code generated by protoc-gen-go. DO NOT EDIT.\npackage x\n"));
    assert.ok(looksGenerated("# Generated by the protocol buffer compiler.  DO NOT EDIT!\n"));
    assert.ok(looksGenerated("// @generated by cargo\n"));
    assert.ok(looksGenerated("'------\n' <auto-generated>\n'     This code was generated by a tool.\n"));
    assert.ok(looksGenerated("/* eslint-disable */\n// This file was automatically generated. Do not edit.\n"));
  });

  test("手で直すことのあるもの・注意書きだけのものは生成コードとみなさない", () => {
    // Django のマイグレーション(依存の名前を新しいマイグレーションで使う)
    assert.ok(!looksGenerated("# Generated by Django 5.1 on 2026-11-02 10:00\nfrom django.db import migrations\n"));
    assert.ok(!looksGenerated("// Do not edit this function without updating the docs\nexport function f() {}\n"));
    // 先頭の 15 行より後の印は見ない
    assert.ok(!looksGenerated(`${"x\n".repeat(20)}// Code generated. DO NOT EDIT.\n`));
  });

  test("文書(.md)は印があっても外さない", () => {
    const { result } = plan({
      "README.md": "# x\nThe files under gen/ are generated. Do not edit them by hand.\n",
      "src/a.py": "x = 1\n",
    });
    assert.deepStrictEqual(result.exclude, []);
    assert.ok(packed(result, "README.md"));
  });
});
